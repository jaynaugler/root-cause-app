<script lang="ts">
	import * as Card from '#lib/components/ui/card/index.js';

	let {
		summary,
		provider,
		anchorPrefix
	}: {
		summary: string | null;
		provider?: string | null;
		// citation [n] links to #{anchorPrefix}{n} — unique per thread turn
		anchorPrefix: string;
	} = $props();

	// Split "…in 2018. [1] She… [2]" into text and citation parts:
	// ["…in 2018. ", "1", " She… ", "2", ""] — odd indexes are the citation numbers.
	const parts = $derived(summary ? summary.split(/\[(\d+)\]/) : []);
</script>

<Card.Root>
	<Card.Header>
		<Card.Title class="text-base">Summary</Card.Title>
	</Card.Header>
	<Card.Content>
		{#if summary}
			<p class="leading-relaxed">
				{#each parts as part, i}
					{#if i % 2 === 1}
						<!-- [n] links to the result card with id="{anchorPrefix}n" -->
						<a
							href="#{anchorPrefix}{part}"
							class="mx-0.5 inline-flex h-5 min-w-5 items-center justify-center rounded-full bg-muted px-1.5 align-text-top text-xs font-medium hover:bg-primary hover:text-primary-foreground"
							>{part}</a
						>
					{:else}
						{part}
					{/if}
				{/each}
			</p>
		{:else}
			<p class="text-sm text-muted-foreground">No summary available for this search.</p>
		{/if}
		{#if provider}
			<p class="pt-3 text-xs text-muted-foreground">Generated by {provider} from the records below</p>
		{/if}
	</Card.Content>
</Card.Root>
