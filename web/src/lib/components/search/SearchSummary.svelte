<script lang="ts">
	import * as Card from '#lib/components/ui/card/index.js';

	let {
		summary,
		provider,
		anchorPrefix,
		stale = false,
		updating = false,
		status = null
	}: {
		summary: string | null;
		provider?: string | null;
		// citation [n] links to #{anchorPrefix}{n} — unique per thread turn
		anchorPrefix: string;
		// Written for other records (a filter changed them): dimmed, and [n] are no longer links,
		// because [1] would now point to a different record
		stale?: boolean;
		// A new summary for the current records is being written
		updating?: boolean;
		// After a filter change has fully arrived (newest answer only): `shown` is added to the
		// subtitle ("updated for 2 filters"), `spoken` is read out by screen readers
		status?: { shown: string; spoken: string } | null;
	} = $props();

	// Split "…in 2018. [1] She… [2]" into text and citation parts:
	// ["…in 2018. ", "1", " She… ", "2", ""] — odd indexes are the citation numbers.
	const parts = $derived(summary ? summary.split(/\[(\d+)\]/) : []);

	// The subtitle: where the summary comes from, plus the status after a filter change
	const source = $derived(
		stale
			? updating
				? 'Updating the summary for the new filters…'
				: 'Written before the filters changed'
			: provider
				? `Generated by ${provider} from the records below`
				: ''
	);
	const statusText = $derived(
		!status || stale
			? ''
			: source
				? ` · ${status.shown}`
				: status.shown.charAt(0).toUpperCase() + status.shown.slice(1)
	);
</script>

<!-- A "live region" (role="status"): screen readers read its text out once, when it changes,
     without moving the focus. Always in the page, even empty: a live region that appears
     together with its text is often not read out. Hidden on screen (sr-only). -->
<p role="status" class="sr-only">{status?.spoken ?? ''}</p>

<Card.Root class={stale ? 'opacity-60' : ''}>
	<Card.Header>
		<Card.Title class="text-base">Summary</Card.Title>
		{#if source || statusText}
			<!-- The pulse stops for people who asked for less motion (the text still says it) -->
			<Card.Description class={stale && updating ? 'animate-pulse motion-reduce:animate-none' : ''}>
				{source}{statusText}
			</Card.Description>
		{/if}
	</Card.Header>
	<Card.Content>
		{#if summary}
			<p class="leading-relaxed">
				{#each parts as part, i}
					{#if i % 2 === 1 && stale}
						<!-- same look, but not a link: the records it referred to have changed -->
						<span
							class="mx-0.5 inline-flex h-5 min-w-5 items-center justify-center rounded-full bg-muted px-1.5 align-text-top text-xs font-medium"
							>{part}</span
						>
					{:else if i % 2 === 1}
						<!-- [n] links to the result card with id="{anchorPrefix}n" -->
						<a
							href="#{anchorPrefix}{part}"
							class="mx-0.5 inline-flex h-5 min-w-5 items-center justify-center rounded-full bg-muted px-1.5 align-text-top text-xs font-medium hover:bg-primary hover:text-primary-foreground"
							>{part}</a
						>
					{:else}
						{part}
					{/if}
				{/each}
			</p>
		{:else}
			<p class="text-sm text-muted-foreground">No summary available for this search.</p>
		{/if}
	</Card.Content>
</Card.Root>
